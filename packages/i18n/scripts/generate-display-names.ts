// Writes the names of the supported countries and of the languages people
// can say they speak, in every app language, from the CLDR data in Node.js.
// Hermes (the app's JavaScript engine) has no Intl.DisplayNames, so the names
// ship as data. Run after changing supportedCountries or spokenLanguages:
//   pnpm --filter @shareride/i18n generate:names
import { writeFileSync } from "node:fs";
import { spokenLanguages, supportedCountries } from "@shareride/domain";
import { locales } from "../src/locales.ts";

function write(file: string, lines: string[]): void {
  writeFileSync(new URL(`../src/${file}`, import.meta.url), [...lines, ""].join("\n"));
}

const countries = [
  "// Generated by scripts/generate-display-names.ts from CLDR data. Do not edit.",
  'import type { SupportedCountry } from "@shareride/domain";',
  'import type { Locale } from "./locales.ts";',
  "",
  "export const countryNames: Readonly<Record<Locale, Readonly<Record<SupportedCountry, string>>>> = {",
];
for (const locale of locales) {
  const names = new Intl.DisplayNames([locale], { type: "region" });
  countries.push(`  ${locale}: {`);
  for (const country of supportedCountries) {
    countries.push(`    ${country}: ${JSON.stringify(names.of(country))},`);
  }
  countries.push("  },");
}
countries.push("};");
write("country-names.generated.ts", countries);

const languages = [
  "// Generated by scripts/generate-display-names.ts from CLDR data. Do not edit.",
  'import type { SpokenLanguage } from "@shareride/domain";',
  'import type { Locale } from "./locales.ts";',
  "",
  "export const languageNames: Readonly<Record<Locale, Readonly<Record<SpokenLanguage, string>>>> = {",
];
for (const locale of locales) {
  const names = new Intl.DisplayNames([locale], { type: "language" });
  languages.push(`  ${locale}: {`);
  for (const language of spokenLanguages) {
    const name = names.of(language) ?? language;
    // Shown as labels, so capitalised; Icelandic writes language names in lower case.
    const label = name.charAt(0).toLocaleUpperCase(locale) + name.slice(1);
    languages.push(`    ${language}: ${JSON.stringify(label)},`);
  }
  languages.push("  },");
}
languages.push("};");
write("language-names.generated.ts", languages);
